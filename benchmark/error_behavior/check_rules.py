# The examples the rule table names, each a row of the survey.
DOMAIN = [("Gamma_Cumulative", "negative", "Shape", "#NUM!"),
          ("Normal_Cumulative", "zero", "StdDev", "#NUM!"),
          ("Beta_InverseCumulative", "below", "Probability", "#NUM!"),
          ("Beta_InverseCumulative", "above", "Probability", "#NUM!"),
          ("Gamma_Cumulative", "zero", "X", "number"),
          ("Normal_Cumulative", "negative", "Mean", "number")]


class RuleError(Exception):
    pass


def read_grid(path=build_grid.FILE):
    with open(path, encoding="utf-8", newline="") as handle:
        return list(csv.DictReader(handle))


def kind(cell):
    """number, an error name, or what else the survey recorded."""
    if len(cell) == 16 and all(c in "0123456789ABCDEF" for c in cell):
        number = struct.unpack("<d", struct.pack("<Q", int(cell, 16)))[0]
        return "number" if math.isfinite(number) else "non-finite"
    return cell


def rule_failures(rows):
    failures = []
    zero = {(r["function"], r["argument"]): r["observed"] for r in rows if r["class"] == "zero"}
    for row in rows:
        name, label, observed = row["function"], row["class"], kind(row["observed"])
        where = f"{row['point_id']} {name} {label} {row['argument']}".strip()
        if not row["observed"].strip():
            failures.append(f"{where}: not exported")
            continue
        if name == FAST:
            continue
        array = name == ARRAY and observed.startswith("TYPE")
        if label == "valid" and not (observed == "number" or array):
            failures.append(f"R1 {where}: {observed}")
        if label in ("nan", "pinf", "ninf") and observed != "#NUM!":
            failures.append(f"R2 {where}: {observed}")
        if label == "text" and observed != "#VALUE!":
            failures.append(f"R3 {where}: {observed}")
        if label == "empty":
            other = zero[(name, row["argument"])]
            same = row["observed"] == other or (array and kind(other).startswith("TYPE"))
            if not same:
                failures.append(f"R4 {where}: {observed}, and {kind(other)} for zero")
        if label in ("below", "above") and observed != "#NUM!":
            failures.append(f"R5 {where}: {observed}")
        if observed.startswith("RAISED") or observed == "non-finite":
            failures.append(f"R6 {where}: {observed}")
        if observed not in ("number", "#NUM!", "#VALUE!") and not array:
            failures.append(f"R7 {where}: {observed}")
    return failures


def edge_failures(rows):
    found = {(r["function"], r["class"], r["argument"]): kind(r["observed"]) for r in rows}
    failures = []
    for statement, claims, _ in EDGES + [("the rule table", DOMAIN, "")]:
        for suffix, label, argument, expected in claims:
            observed = found.get(("K_STATS_" + suffix, label, argument))
            if observed != expected:
                failures.append(f"edge {suffix} {label} {argument}: stated {expected}, "
                                f"observed {observed} ({statement[:40]}...)")
    return failures


def fast_statement(rows):
    """What the exempt function does, read from the grid."""
    found = {r["class"]: kind(r["observed"]) for r in rows if r["function"] == FAST}
    expected = {"nan": "RAISED6", "below": "number", "above": "number", "pinf": "number",
                "ninf": "number", "text": "#VALUE!", "valid": "number"}
    wrong = {k: found.get(k) for k, v in expected.items() if found.get(k) != v}
    if wrong:
        raise RuleError(f"{FAST} no longer behaves as the page says: {wrong}")
    return ("`K_STATS_NormalStandard_InverseCumulativeFast` is the one exception. It returns a "
            "`Double`, not a worksheet value, and validates nothing: a probability outside 0 to 1, "
            "or an infinity, is clipped and a number comes back, and a not-a-number raises "
            "run-time error 6. It is a helper for simulation loops, documented so in its "
            "header; use `K_STATS_NormalStandard_InverseCumulative` in a worksheet.")


def render(rows):
    failures = rule_failures(rows) + edge_failures(rows)
    if failures:
        raise RuleError(f"{len(failures)} row(s) break a rule or an edge: {failures[0]}")
    out = [BEGIN, "",
           "## What a function returns on bad input", "",
           "The rules below hold for every public function. They are not asserted here: a "
           "survey calls each function with each kind of input in Excel "
           "(`benchmark/error_behavior/`), this section is generated from what came back, and "
           "a battery in the VBA suite, `Test_Core_ApiErrorContract`, checks the first two "
           "rules on every function at every regression.", "",
           "| Input | Returned | Why |", "| --- | --- | --- |",
           "| A valid call | A number | Never an error |",
           "| An argument that is not a number, or is infinite | `#NUM!` | Only VBA code can "
           "pass one; a cell cannot hold it |",
           "| A parameter outside its domain: a negative shape, a zero standard deviation, a "
           "probability below 0 or above 1 | `#NUM!` | The request is outside the mathematical "
           "contract |",
           "| An argument beyond the tested magnitude, or a result that is not a finite number "
           "| `#NUM!` | See the limits of each family in the README |",
           "| A text | `#VALUE!` | Excel refuses to convert it, before the function is called |",
           "| An empty cell | What 0 returns | Excel passes an empty cell as the number zero |",
           "| An error the function did not foresee | `#VALUE!`, with the reason in `Status` "
           "| None is known; the survey found none |",
           "",
           "No function raises a VBA error, returns an infinity or a not-a-number, or returns "
           "any other worksheet error.", "",
           "`K_STATS_Lognormal_ParametersFromMeanStdDev` returns two numbers as an array, and "
           "follows the same rules.", "",
           fast_statement(rows), "",
           "### Where functions answer the same input differently", "",
           "Read from the same survey. \"Kept\" is deliberate. \"Not settled\" is a difference "
           "I found and have not decided; it is recorded in #418 and may change in a "
           "later release.", "",
           "| What happens | Status |", "| --- | --- |"]
    out += [f"| {statement} | {reason} |" for statement, _, reason in EDGES]
    out += ["", END]
    return "\n".join(out)


def replace_section(page, section):
    if page.count(BEGIN) != 1 or page.count(END) != 1:
        raise RuleError("docs/PUBLIC_API.md must hold the two markers once each")
    start, stop = page.index(BEGIN), page.index(END) + len(END)
    return page[:start] + section + page[stop:]


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    rows = read_grid()
    failures = rule_failures(rows) + edge_failures(rows)
    for text in failures[:40]:
        print(f"FAIL: {text}")
    if failures:
        print(f"FAIL: {len(failures)} finding(s)")
        return 1
    try:
        section = render(rows)
        if a.write or a.check:
            with open(PAGE, encoding="utf-8") as handle:
                page = handle.read()
            updated = replace_section(page, section)
            if a.check and updated != page:
                print("FAIL: the section of docs/PUBLIC_API.md is not current; run --write")
                return 1
            if a.write:
                with open(PAGE, "w", encoding="utf-8", newline="") as handle:
                    handle.write(updated)
    except RuleError as problem:
        print(f"FAIL: {problem}")
        return 1
    print(f"PASS: the rules and the edges hold on {len(rows)} calls")
    return 0


if __name__ == "__main__":
    sys.exit(main())
