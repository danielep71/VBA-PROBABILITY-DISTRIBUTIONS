"""
#331: the error rules of the public surface, checked against the survey and
written into docs/PUBLIC_API.md.

error_behavior_grid.csv holds what Excel returned for every call of the
survey. This program states the rules, fails if one row breaks them, and
generates the section of the page from the same statements, so the page
cannot say what the survey does not show.

Rules, for every public function but the one of NOT_VALIDATING:

  R1  a valid call returns a value, never an error;
  R2  an argument that is not a number, or is infinite, returns #NUM!;
  R3  a text argument returns #VALUE!;
  R4  an empty cell is the number zero: the call returns what it returns
      for 0;
  R5  a probability below 0 or above 1 returns #NUM!;
  R6  nothing raises a VBA error, and no result is infinite or not a number;
  R7  the only worksheet errors returned are #NUM! and #VALUE!.

EDGES are the places where functions of one family, or of two families,
answer the same kind of input differently. Each is a statement about the
grid, checked here, with the reason it is so or the note that it is not
settled.

Run:
    python3 check_rules.py            check the rules and the edges
    python3 check_rules.py --write    also rewrite the section of the page
    python3 check_rules.py --check    also fail if the section is not current
"""
