"""
#330: the table of docs/PUBLIC_API.md, from function_map.py and from what
Excel returned for each example (excel_function_map_grid.csv).

The table states two things about every example that are checked here, not
written by hand:

  the library's value   observed_kstats must agree with the reference from
                        60-digit arithmetic within GUARANTEE, the inverse
                        guarantee of the accuracy policy, which is the
                        loosest tier. Otherwise the page is not written.
  Excel's value         shown as "same" where observed_excel agrees with
                        that reference within SAME, and with its value and
                        its relative difference where it does not.

The probes are reported as measured: for a fractional degree of freedom or
count, whether each side uses the fraction, rounds it down or refuses it.

Run:
    python3 render_map.py --write   rewrite the section between the markers
    python3 render_map.py --check   fail if the section is not current
"""
import argparse
import csv
import os
import struct
import sys

import mpmath as mp

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import function_map  # noqa: E402
import references  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(HERE))
GRID = os.path.join(HERE, "excel_function_map_grid.csv")
PAGE = os.path.join(ROOT, "docs", "PUBLIC_API.md")
BEGIN = "<!-- BEGIN excel-function-map: generated by benchmark/excel_function_map/render_map.py -->"
END = "<!-- END excel-function-map -->"
GUARANTEE = mp.mpf("1e-12")
SAME = mp.mpf("1e-12")
PROBE_MATCH = mp.mpf("1e-9")


class MapError(Exception):
    pass


def read_grid(path=GRID):
    with open(path, encoding="utf-8", newline="") as handle:
        return list(csv.DictReader(handle))


def value(cell):
    """The Double of an observation cell, or None for ERROR."""
    if cell == "ERROR":
        return None
    if len(cell) != 16:
        raise MapError(f"not an observation: {cell!r}; has the grid been exported?")
    return mp.mpf(struct.unpack("<d", struct.pack("<Q", int(cell, 16)))[0])


def relative(observed, reference):
    return abs(observed - reference) if reference == 0 else abs((observed - reference) / reference)


def shown(number):
    text = mp.nstr(number, 12, strip_zeros=True, min_fixed=-5, max_fixed=15)
    return text[:-2] if text.endswith(".0") else text


def code(text):
    return "`" + text + "`"


def observations(grid):
    return {(row["excel_formula"].replace(";", ","), row["kstats_call"].replace(";", ",")): row
            for row in grid}


def example_cells(row, found):
    excel, kstats = row["example"]
    observed = found.get((excel, kstats))
    if observed is None:
        raise MapError(f"no grid row for {excel}")
    reference = mp.mpf(observed["reference"])
    library = value(observed["observed_kstats"])
    if library is None:
        raise MapError(f"the library returns an error for {kstats}")
    if relative(library, reference) > GUARANTEE:
        raise MapError(f"{kstats}: the library returns {shown(library)}, the reference is "
                       f"{shown(reference)}")
    native = value(observed["observed_excel"])
    if native is None:
        excel_text = "an error"
    elif relative(native, reference) <= SAME:
        excel_text = "same"
    elif native == 0:
        excel_text = "0: the value is lost"
    else:
        excel_text = f"{shown(native)}, off by {mp.nstr(relative(native, reference), 2)}"
    return f"{code('=' + excel)}<br>{code('=' + kstats)}", shown(reference), excel_text


def probe_finding(observed_cell, fraction, truncated):
    observed = value(observed_cell)
    if observed is None:
        return "refuses it"
    uses = relative(observed, fraction) <= PROBE_MATCH
    truncates = relative(observed, truncated) <= PROBE_MATCH
    if uses and truncates:
        return "rounds it down"
    if uses:
        return "uses the fraction"
    if truncates:
        return "rounds it down"
    return f"returns {shown(observed)}, which is neither"


def render(grid):
    found = observations(grid)
    out = [BEGIN, "",
           "## Coming from Excel's functions", "",
           "One row for each of Excel's distribution functions that the library replaces: "
           "the call that replaces it, what differs, and an example. Both formulas of "
           "every example were evaluated in Excel; the value shown is the library's, checked "
           "against 60-digit arithmetic, and the last column says whether Excel's own "
           "function returned the same number to twelve digits.", "",
           "The library's functions take no cumulative flag: the name says which function "
           "it is. Every one takes an optional last argument, `Status`, that receives a "
           "diagnostic text.", ""]
    families = []
    for row in function_map.ROWS:
        if row["family"] not in families:
            families.append(row["family"])
    for family in families:
        out += [f"### {family}", "",
                "| Excel | Library | What differs | Example | Value | Excel returns |",
                "| --- | --- | --- | --- | ---: | --- |"]
        for row in function_map.ROWS:
            if row["family"] != family:
                continue
            example, number, excel_text = example_cells(row, found)
            legacy = f"<br>also {code(row['legacy'])}" if row["legacy"] else ""
            out.append(f"| {code(row['excel'])}{legacy} | {code(row['kstats'])} | {row['notes']} "
                       f"| {example} | {number} | {excel_text} |")
        out.append("")

    out += ["### Fractional degrees of freedom and counts", "",
            "Measured, not taken from either documentation: the same call on both sides with "
            "a fractional argument. Where the two columns differ, the two results differ: "
            "an Excel function that rounds a degree of freedom down computes a different "
            "distribution from the one the library computes at the fraction.", "",
            "| Case | Excel formula | Excel | Library |", "| --- | --- | --- | --- |"]
    for probe in function_map.PROBES:
        observed = found.get((probe["excel"], probe["kstats"]))
        if observed is None:
            raise MapError(f"no grid row for {probe['excel']}")
        fraction = references.evaluate(probe["kstats"])
        truncated = references.evaluate(probe["truncated"])
        out.append(f"| {probe['topic']} | {code('=' + probe['excel'])} "
                   f"| {probe_finding(observed['observed_excel'], fraction, truncated)} "
                   f"| {probe_finding(observed['observed_kstats'], fraction, truncated)} |")

    out += ["", "### Where a replacement stops applying", "",
            "The Excel formula and the library expression a row above would give, both "
            "evaluated as they stand. The rows above give the form to use instead.", "",
            "| Case | Excel formula | Excel returns | Library expression | Library returns |",
            "| --- | --- | --- | --- | --- |"]
    for edge in function_map.EDGES:
        observed = found.get((edge["excel"], edge["kstats"]))
        if observed is None:
            raise MapError(f"no grid row for {edge['excel']}")
        cells = []
        for key in ("observed_excel", "observed_kstats"):
            number = value(observed[key])
            cells.append("an error" if number is None else shown(number))
        out.append(f"| {edge['topic']} | {code('=' + edge['excel'])} | {cells[0]} "
                   f"| {code('=' + edge['kstats'])} | {cells[1]} |")

    out += ["", "### Excel functions the library does not replace", "",
            "| Excel | Why |", "| --- | --- |"]
    out += [f"| {names} | {why} |" for names, why in function_map.WITHOUT_COUNTERPART]
    out += ["", "### Library functions Excel has no function for", "",
            "| What | Functions |", "| --- | --- |"]
    out += [f"| {what} | {functions} |" for what, functions in function_map.LIBRARY_ONLY]
    out += ["", END]
    return "\n".join(out)


def replace_section(page, section):
    if page.count(BEGIN) != 1 or page.count(END) != 1:
        raise MapError("docs/PUBLIC_API.md must hold the two markers once each")
    start, stop = page.index(BEGIN), page.index(END) + len(END)
    return page[:start] + section + page[stop:]


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    try:
        section = render(read_grid())
        with open(PAGE, encoding="utf-8") as handle:
            page = handle.read()
        updated = replace_section(page, section)
    except MapError as problem:
        print(f"FAIL: {problem}")
        return 1
    if a.check:
        if updated != page:
            print("FAIL: the section of docs/PUBLIC_API.md is not current; run --write")
            return 1
        print("PASS: the Excel function map of docs/PUBLIC_API.md is current")
        return 0
    with open(PAGE, "w", encoding="utf-8", newline="") as handle:
        handle.write(updated)
    print("wrote docs/PUBLIC_API.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
