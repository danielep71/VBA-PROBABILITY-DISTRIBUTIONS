#!/usr/bin/env python3
"""Freeze and verify the worksheet-facing VBA product API.

The product API is the set of Public K_STATS_* declarations in the six
production modules under src/. Benchmark/test Public Subs are deliberately out
of scope. Project-scoped PROB_* routines are also out of scope: they may be
Public inside Option Private Module modules so production modules can share
numerical kernels without exposing them in Excel's Function Wizard.

The manifest is readable text, not a digest, so an intentional API change shows
exactly which declaration changed. Formatting and procedure-body edits do not
change the normalized declaration.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "docs" / "PUBLIC_API.txt"
MODULES = (
    "src/M_STATS_PROBDIST_CORE.bas",
    "src/M_STATS_PROBDIST_SPECIALFUNCS.bas",
    "src/M_STATS_PROBDIST_NORMALFAMILY.bas",
    "src/M_STATS_PROBDIST_TFAMILY.bas",
    "src/M_STATS_PROBDIST_CONTINUOUS.bas",
    "src/M_STATS_PROBDIST_DISCRETE.bas",
)
HEADER = (
    "# VBA-PROBABILITY-DISTRIBUTIONS public API v1\n"
    "# <module><TAB><kind><TAB><name><TAB><normalized declaration>\n"
    "# Product API = K_STATS_* declarations only. PROB_* project helpers and benchmark/test exporters are excluded.\n"
    "# Generated by benchmark/check_public_api.py --write; edit only for an intentional API change.\n"
)

DECL_RE = re.compile(
    r"^Public\s+(?:(Static)\s+)?(Function|Sub|Property\s+(?:Get|Let|Set)|Const)\s+"
    r"([A-Za-z_][A-Za-z0-9_]*)\b(.*)$",
    re.IGNORECASE,
)


class ApiError(ValueError):
    pass


def strip_comment(line: str) -> str:
    """Remove VBA apostrophe comments outside string literals."""
    out = []
    in_string = False
    i = 0
    while i < len(line):
        ch = line[i]
        if ch == '"':
            out.append(ch)
            if in_string and i + 1 < len(line) and line[i + 1] == '"':
                out.append('"')
                i += 2
                continue
            in_string = not in_string
            i += 1
            continue
        if ch == "'" and not in_string:
            break
        out.append(ch)
        i += 1
    return "".join(out).rstrip()


def logical_lines(text: str) -> list[str]:
    """Join VBA physical lines linked by a terminal line-continuation `_`."""
    result: list[str] = []
    pending = ""
    for raw in text.replace("\r\n", "\n").replace("\r", "\n").split("\n"):
        clean = strip_comment(raw).strip()
        if not clean:
            if pending:
                result.append(pending.strip())
                pending = ""
            continue
        continued = bool(re.search(r"\s_\s*$", clean))
        if continued:
            clean = re.sub(r"\s_\s*$", "", clean).rstrip()
        pending = (pending + " " + clean).strip() if pending else clean
        if not continued:
            result.append(pending.strip())
            pending = ""
    if pending:
        raise ApiError("unterminated VBA line continuation")
    return result


def normalize_signature(decl: str) -> str:
    """Canonicalize declaration whitespace without changing VBA semantics."""
    value = re.sub(r"\s+", " ", decl.strip())
    value = re.sub(r"\s*\(\s*", "(", value)
    value = re.sub(r"\s*\)", ")", value)
    value = re.sub(r"\s*,\s*", ", ", value)
    value = re.sub(r"\s*=\s*", " = ", value)
    return value.strip()


def declarations_from_text(module: str, text: str) -> list[tuple[str, str, str, str]]:
    api: list[tuple[str, str, str, str]] = []
    for line in logical_lines(text):
        match = DECL_RE.match(line)
        if not match:
            continue
        static, kind, name, _ = match.groups()
        if not name.upper().startswith("K_STATS_"):
            continue
        kind = re.sub(r"\s+", " ", kind).title()
        if static:
            kind = "Static " + kind
        api.append((module, kind, name, normalize_signature(line)))
    return api


def collect(root: Path) -> list[tuple[str, str, str, str]]:
    all_api: list[tuple[str, str, str, str]] = []
    for rel in MODULES:
        path = root / rel
        if not path.is_file():
            raise ApiError(f"required production module missing: {rel}")
        all_api.extend(declarations_from_text(rel, path.read_text(encoding="utf-8-sig")))
    if not all_api:
        raise ApiError("no public K_STATS_* declarations found")
    names = [item[2].casefold() for item in all_api]
    dup = sorted({name for name in names if names.count(name) > 1})
    if dup:
        raise ApiError("duplicate public API name(s): " + ", ".join(dup))
    return sorted(all_api, key=lambda item: (item[0].casefold(), item[2].casefold(), item[1].casefold()))


def render(entries: list[tuple[str, str, str, str]]) -> str:
    rows = [HEADER.rstrip("\n")]
    rows.extend("\t".join(item) for item in entries)
    return "\n".join(rows) + "\n"


def compare(expected: str, actual: str) -> list[str]:
    e = expected.replace("\r\n", "\n").splitlines()
    a = actual.replace("\r\n", "\n").splitlines()
    if e == a:
        return []
    e_rows = {line.split("\t", 3)[2].casefold(): line for line in e if "\t" in line}
    a_rows = {line.split("\t", 3)[2].casefold(): line for line in a if "\t" in line}
    findings: list[str] = []
    for key in sorted(set(e_rows) - set(a_rows)):
        findings.append("removed public API: " + e_rows[key])
    for key in sorted(set(a_rows) - set(e_rows)):
        findings.append("added public API: " + a_rows[key])
    for key in sorted(set(e_rows) & set(a_rows)):
        if e_rows[key] != a_rows[key]:
            findings.append("changed public API:\n    expected: " + e_rows[key] + "\n    actual:   " + a_rows[key])
    if not findings:
        findings.append("manifest formatting/header differs from generated canonical form")
    return findings


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--manifest", type=Path, default=None)
    parser.add_argument("--write", action="store_true", help="write the canonical manifest from current source")
    parser.add_argument("--print", action="store_true", dest="print_manifest", help="print the canonical manifest")
    args = parser.parse_args(argv)
    root = args.root.resolve()
    manifest = args.manifest or (root / "docs" / "PUBLIC_API.txt")
    try:
        entries = collect(root)
        actual = render(entries)
        if args.print_manifest:
            print(actual, end="")
        if args.write:
            manifest.parent.mkdir(parents=True, exist_ok=True)
            manifest.write_text(actual, encoding="utf-8", newline="\n")
            print(f"wrote {manifest}: {len(entries)} public declaration(s)")
            return 0
        if not manifest.is_file():
            print("FAIL: public VBA API manifest is missing")
            print(f"  expected: {manifest}")
            print("--- GENERATED PUBLIC API ---")
            print(actual, end="")
            print("--- END GENERATED PUBLIC API ---")
            return 1
        expected = manifest.read_text(encoding="utf-8-sig")
        findings = compare(expected, actual)
        if findings:
            print("FAIL: public VBA API drift")
            for finding in findings:
                print("  - " + finding)
            return 1
    except (OSError, UnicodeError, ApiError) as exc:
        print("FAIL: public VBA API check")
        print("  - " + str(exc))
        return 1
    print(f"PASS: public VBA API ({len(entries)} K_STATS_* declaration(s))")
    return 0


if __name__ == "__main__":
    sys.exit(main())
